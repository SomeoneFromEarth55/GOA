#შექმენი ცვლადი number, რომელშიც მომხმარებელი შეიტანს რაიმე მთელ რიცხვს (input()-ით). გამოიყენე ნაშთიანი გაყოფა (% 2), რათა შეამოწმო არის თუ არა რიცხვი ლუწი. თუ ნაშთი უდრის 0-ს, დაბეჭდე „რიცხვი ლუწია“, ხოლო სხვა შე მთხვევაში (else) — „რიცხვი კენტია“.
number_1=int(input("შეიყვაეთ რამე მთელი რიცხვი "))
if number_1%2==0:
    print ("ეს რიცხვი არის ლუწი")
else:
    print("ეს რიცხვი არის კენტი")