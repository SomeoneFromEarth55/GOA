#დავალება 3: ასაკობრივი შეზღუდვა  | შედარების ოპერატორები (>=, if-else) (მარტივი)
#შექმენი ცვლადი age, სადაც მომხმარებელი შეიტანს საკუთარ ასაკს. დაწერე პირობა: თუ ასაკი მეტია ან ტოლი 18-ზე (age >= 18), დაბეჭდე „მოგესალმებით, თქვენ სრულწლოვანი ხართ!“, წინააღმდეგ შემთხვევაში დაბეჭდე „შესვლა შეზღუდულია!“.
age=int(input("შეიყვანეთ თქვენი ასაკი"))
if age >= 18:
    print ("მოგესალმებით თქვენ სრულწლოვანი ხართ")
else:
    print ("შესვლა აკრძალულია")